import { chromium } from 'playwright-core';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const browser = await chromium.launch({channel:'chrome',headless:true});
const context = await browser.newContext({viewport:{width:1440,height:1000}});
const cookie = JSON.parse(fs.readFileSync('.cache/multiple-filters/session.json','utf8'));
await context.addCookies([{...cookie,domain:'127.0.0.1',path:'/'}]);
const page = await context.newPage();
const errors = [];
page.on('pageerror',error => errors.push(error.message));
const loaded = () => page.waitForFunction(() => document.getElementById('dvPanel').getAttribute('aria-busy') === 'false' && document.getElementById('dvRetry').hidden);
try {
    await page.goto('http://127.0.0.1:8011/',{waitUntil:'networkidle'});
    await page.locator('[data-open-desvios="positivo"]').waitFor();
    await page.waitForFunction(() => !document.querySelector('[data-open-desvios]').disabled);
    const original = await page.evaluate(() => ({query:buildQuery(),kpi:document.getElementById('kpiDesvio').textContent}));
    const existing = await page.evaluate(async () => (await (await fetch('/api/por-cliente' + buildQuery())).json()).clientes);
    assert.equal(Number(await page.locator('#dvPositiveCount').innerText()),existing.filter(item => item.desvio > .005).length);
    assert.equal(Number(await page.locator('#dvNegativeCount').innerText()),existing.filter(item => item.desvio < -.005).length);
    for (const direction of ['positivo','negativo']) {
        await page.locator(`[data-open-desvios="${direction}"]`).click();
        await loaded();
        assert.equal(await page.locator('.dv-accounts-grid .dv-explore-card').count(),existing.filter(item => direction === 'positivo' ? item.desvio > .005 : item.desvio < -.005).length);
        assert((await page.locator('.dv-accounts-grid .dv-sign').allTextContents()).every(text => text.includes(direction)));
        assert.equal(await page.locator('#dvPanel table').count(),0);
        await page.screenshot({path:`.cache/multiple-filters/dashboard-${direction}-cards.png`});
        await page.locator('[data-dv-client-campaigns]').first().click();
        await loaded();
        assert(await page.locator('.dv-campaign-grid').isVisible());
        assert.equal(await page.locator('#dvDirection').inputValue(),direction);
        const campaignName = await page.locator('.dv-campaign-grid strong').first().innerText();
        await page.locator('[data-dv-campaign]').first().click();
        assert.equal(await page.locator('.dv-account').innerText(),campaignName);
        await page.locator('[data-dv-back-campaigns]').click();
        await page.locator('[data-dv-back-clients]').click();
        await loaded();
        assert.equal(await page.locator('#dvDirection').inputValue(),direction);
        assert(await page.locator('.dv-accounts-grid').isVisible());
        await page.keyboard.press('Escape');
    }
    await page.locator('[data-open-desvios="positivo"]').click();
    await loaded();
    assert(await page.locator('#dashboardDesviosDialog').evaluate(dialog => dialog.open));
    assert.equal(await page.locator('#dvDirection').inputValue(),'positivo');
    assert.equal(await page.locator('#dvAdvanced').evaluate(details => details.open),false);
    assert.equal(await page.locator('#dvYear').isVisible(),false);
    assert.equal(await page.locator('#dvDetail').isVisible(),false);
    assert(await page.locator('.dv-accounts-grid').isVisible());
    await page.locator('#dvDirection').selectOption('negativo');
    await loaded();
    assert((await page.locator('.dv-accounts-grid .dv-sign').allTextContents()).every(text => text.includes('negativo')));
    await page.locator('#dvReset').click();
    await loaded();
    await page.locator('[data-dv-client-campaigns]').first().click();
    await loaded();
    assert.equal(await page.locator('#dvTabCampanias').getAttribute('aria-selected'),'true');
    const selectedClient = await page.locator('#dvClient').inputValue();
    const campaignData = await page.evaluate(async () => {
        const query = new URLSearchParams(buildQuery());
        query.set('cliente_grupo',document.getElementById('dvClient').value);
        query.set('apertura','campanias');
        return (await (await fetch('/api/dashboard/desvios?' + query.toString())).json()).clientes[0];
    });
    assert.equal(await page.locator('.dv-campaign-grid .dv-explore-card').count(),campaignData.campanias.length);
    await page.screenshot({path:'.cache/multiple-filters/dashboard-campaigns-desktop.png'});
    await page.locator('[data-dv-campaign]').first().click();
    assert.equal(await page.locator('.dv-account').innerText(),campaignData.campanias[0].nombre);
    assert.equal(await page.locator('.dv-total .dv-period').innerText(),await page.evaluate(value => `${value < 0 ? '−' : ''}$ ${Math.abs(value).toLocaleString('es-AR',{minimumFractionDigits:2,maximumFractionDigits:2})}`,campaignData.campanias[0].resumen.desvio));
    assert(await page.locator('#dvCampaignContext').isVisible());
    await page.locator('[data-dv-back-campaigns]').click();
    assert(await page.locator('.dv-campaign-grid').isVisible());
    assert.equal(await page.locator('#dvClient').inputValue(),selectedClient);
    await page.locator('#dvTabClientes').click();
    await page.locator('[data-dv-client]').first().click();
    await loaded();
    assert.equal(await page.locator('#dvTabMensual').getAttribute('aria-selected'),'true');
    assert.equal(await page.locator('.dv-account').count(),1);
    assert((await page.locator('.dv-matrix thead').innerText()).includes('Dic'));
    assert((await page.locator('.dv-matrix').innerText()).includes('Cumplimiento de horas'));
    assert(!(await page.locator('.dv-matrix').innerText()).includes('Cumplimiento de valor hora'));
    const amounts = await page.locator('.dv-matrix tbody tr').evaluateAll(rows => rows.map(row => ({label:row.querySelector('.dv-concept').textContent,amount:row.querySelector('.dv-period').textContent})));
    const parseMoney = text => Number(text.replace(/\./g,'').replace(',','.').replace('−','-').replace(/[^0-9.\-]/g,''));
    const componentTotal = amounts.filter((row,index) => index < 3 || row.label.includes('conciliaci')).reduce((sum,row) => sum + parseMoney(row.amount),0);
    assert(Math.abs(componentTotal - parseMoney(amounts.at(-1).amount)) < .02,'Simplified components must reconcile with the total');
    await page.screenshot({path:'.cache/multiple-filters/dashboard-desvios-simple.png'});
    await page.locator('#dvDetail').check();
    assert((await page.locator('.dv-matrix').innerText()).includes('Horas objetivo'));
    await page.screenshot({path:'.cache/multiple-filters/dashboard-desvios-desktop.png'});
    await page.locator('#dvAdvanced summary').click();
    await page.locator('#dvSearch').fill('nonexistent-ux-client');
    await page.waitForSelector('.dv-empty');
    assert((await page.locator('#dvFilterCount').innerText()).includes('1'));
    await page.mouse.click(1,1);
    assert.equal(await page.locator('#dashboardDesviosDialog').evaluate(dialog => dialog.open),false);
    assert(await page.locator('[data-open-desvios="positivo"]').evaluate(button => button === document.activeElement));
    assert.deepEqual(await page.evaluate(() => ({query:buildQuery(),kpi:document.getElementById('kpiDesvio').textContent})),original);
    await page.locator('[data-open-desvios="mensual"]').click();
    await loaded();
    assert(await page.locator('.dv-picker').isVisible());
    assert.equal(await page.locator('.dv-matrix').count(),0);
    await page.locator('[data-dv-compare]').click();
    assert(await page.locator('.dv-account').count() > 1);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#dashboardDesviosDialog').evaluate(dialog => dialog.open),false);
    await page.route('**/api/dashboard/desvios?*',route => route.fulfill({status:500,body:'{}'}));
    await page.locator('[data-open-desvios="mensual"]').click();
    await page.waitForFunction(() => !document.getElementById('dvRetry').hidden);
    assert.equal(await page.locator('#dvPanel table').count(),0);
    await page.unroute('**/api/dashboard/desvios?*');
    await page.locator('#dvRetry').click();
    await loaded();
    assert(await page.locator('.dv-picker').isVisible());
    await page.locator('[data-dv-client]').first().click();
    await loaded();
    await page.setViewportSize({width:390,height:844});
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    assert(await page.locator('#dashboardDesviosDialog').evaluate(dialog => dialog.getBoundingClientRect().right <= innerWidth));
    assert(await page.locator('#dvClient').evaluate(select => select.getBoundingClientRect().height >= 30));
    await page.locator('#dvTabCampanias').click();
    await loaded();
    await page.screenshot({path:'.cache/multiple-filters/dashboard-campaigns-mobile.png'});
    await page.locator('[data-dv-campaign]').first().click();
    assert(await page.locator('[data-dv-back-campaigns]').isVisible());
    await page.screenshot({path:'.cache/multiple-filters/dashboard-desvios-mobile.png'});
    await page.locator('[data-dv-close]').click();
    assert.equal(errors.length,0,errors.join('\n'));
    console.log('OK: progressive filters, simplified list, client picker, essential/full metrics, compare all, independent filters, empty/error/retry, backdrop/Escape/focus and mobile dialog.');
} finally { await browser.close(); }
