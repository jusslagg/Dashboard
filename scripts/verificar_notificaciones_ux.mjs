import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const nodes = new Map();
const node = id => {
    if (!nodes.has(id)) nodes.set(id, { value: '', textContent: '', innerHTML: '', className: '' });
    return nodes.get(id);
};
const context = vm.createContext({ window: {}, document: { addEventListener() {}, getElementById: node }, console, Date, URLSearchParams });
vm.runInContext(fs.readFileSync('app/static/notificaciones-ux.js', 'utf8'), context);
context.NotificacionesUX = context.window.NotificacionesUX;
const template = fs.readFileSync('app/templates/notificaciones_proyecciones.html', 'utf8');
const source = [...template.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)].map(match => match[1]).find(script => script.includes('let datosNotificaciones'));
vm.runInContext(source, context);
const ux = context.NotificacionesUX;
assert.equal(ux.direction(100), 'sube');
assert.equal(ux.direction(-100), 'baja');
assert.equal(ux.direction(0), 'sin_impacto');
const metric = (anterior, actual) => ({ anterior, actual, diferencia: actual - anterior });
const service = impact => ({ campania: 'Campaña', impacto_facturacion: impact, comparacion: { dotacion_requerida: metric(20, 22), horas_proyectadas: metric(100, 110), precio_final: metric(10, 10) }, cambios: [] });
const client = { cliente: '<Cliente>', mes: '2026-10', mes_label: 'Oct-26', mes_anterior_label: 'Sep-26', impacto_facturacion: 100, facturacion_anterior: 1000, facturacion_actual: 1100, cantidad_servicios: 2, servicios: [service(200), service(-100)], comparacion: service(100).comparacion };
const counts = ux.serviceCounts(client);
assert.equal(counts.sube, 1);
assert.equal(counts.baja, 1);
assert.match(ux.reading(client), /ambas direcciones/);
assert.match(ux.metricChanges(client), /Precio promedio ponderado: sin cambio/);
assert.match(ux.reading({ ...client, impacto_facturacion: 0 }), /compensan/);
const html = context.filaNotificacion(client);
assert.match(html, /Subió el importe/);
assert.match(html, /Movimientos opuestos/);
assert.match(html, /&lt;Cliente&gt;/);
assert(!html.includes('<Cliente>'));
assert.match(context.resumenCambio(client, 'dotacion_requerida', 'numero'), /\+10,00%/);
assert.match(context.resumenCambio({ comparacion: { horas: metric(0, 100) } }, 'horas', 'numero'), /Sin base porcentual/);
assert(!context.resumenCambio({ comparacion: { horas: metric(0, 100) } }, 'horas', 'numero').includes('Infinity'));
assert.match(context.resumenCambio({ comparacion: { horas: metric(10, 5) } }, 'horas', 'numero'), /Bajó/);
assert.match(context.resumenCambio(client, 'precio_final', 'moneda'), /Sin cambio/);
context.notificacionesVisibles = () => [client, { ...client, impacto_facturacion: 0, estado: 'positiva' }, { ...client, impacto_facturacion: -20 }];
context.renderNotificaciones();
assert.equal(node('kpiPositivas').textContent, '1');
assert.equal(node('kpiNegativas').textContent, '1');
assert.equal(node('kpiMixtas').textContent, '1');
assert.match(node('contador').textContent, /cliente\/mes/);
console.log('OK: subida, bajada, neto cero, movimientos opuestos, porcentajes, base cero, KPI y escape HTML.');
