import { chromium } from 'playwright-core';
import fs from 'node:fs';
import assert from 'node:assert/strict';

const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const cookie = JSON.parse(fs.readFileSync('.cache/multiple-filters/session.json', 'utf8'));
await context.addCookies([{ ...cookie, domain: '127.0.0.1', path: '/' }]);
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
    await page.goto('http://127.0.0.1:8011/control', { waitUntil: 'networkidle', timeout: 60000 });
    await page.waitForFunction(() => document.getElementById('estadoControl').dataset.state === 'success');
    const total = await page.evaluate(() => ControlUX.state.rows.length);
    assert(total > 0);
    assert.equal(await page.locator('#tablaDatos > tr').count(), Math.min(total, 50));
    if (total > 50) {
        await page.locator('#controlPaginaSiguiente').click();
        assert.match(await page.locator('#estadoControl').innerText(), /51[–-]/);
        await page.locator('#controlPaginaAnterior').click();
    }
    await page.evaluate(() => {
        ControlUX.state.rows[0].cliente = "O'Connor <nombre>";
        actualizarTabla(ControlUX.state.rows);
    });
    assert.equal(await page.locator('#tablaDatos tr').first().locator('td').nth(2).innerText(), "O'Connor <nombre>");
    await page.locator('#tablaDatos tr').first().getByRole('button', {name: 'Editar', exact: true}).click();
    assert(await page.locator('#modalEditar').evaluate(element => element.open));
    assert.equal(await page.locator('#editCliente').inputValue(), "O'Connor <nombre>");
    await page.locator('#editCliente').fill('Cliente editado');
    page.once('dialog', dialog => dialog.dismiss());
    await page.keyboard.press('Escape');
    assert(await page.locator('#modalEditar').evaluate(element => element.open));
    assert.equal(await page.locator('#editCliente').inputValue(), 'Cliente editado');
    let writes = 0;
    await page.route('**/api/datos/*', async route => {
        if (route.request().method() !== 'PUT') return route.continue();
        writes++;
        await new Promise(resolve => setTimeout(resolve, 300));
        await route.fulfill({ status: 503, contentType: 'application/json', body: '{"success":false,"errores":["Fallo de prueba"]}' });
    });
    await page.locator('#editClave').fill('verification-only');
    await page.locator('#guardarEdicionControlBtn').click();
    await page.evaluate(() => guardarEdicion({preventDefault() {}}));
    await page.waitForFunction(() => !ControlUX.state.saving);
    assert.equal(writes, 1);
    assert.equal(await page.locator('#editCliente').inputValue(), 'Cliente editado');
    assert.match(await page.locator('#errorEdicionControl').innerText(), /Fallo de prueba/);
    assert.equal(await page.locator('#guardarEdicionControlBtn').isEnabled(), true);
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: 'Cerrar edición del registro' }).click();
    assert.equal(await page.locator('#editClave').inputValue(), '');
    await page.screenshot({ path: '.cache/multiple-filters/control-ux.png' });
    await page.setViewportSize({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto('http://127.0.0.1:8011/variable', { waitUntil: 'networkidle' });
    await page.waitForFunction(() => document.getElementById('estadoCargaVariable').dataset.state === 'success');
    await page.locator('#tabNextGen').click();
    const dollar = page.locator('#dolaresNextGen input').first();
    const proposal = String(Number(await dollar.inputValue()) + 1);
    await dollar.fill(proposal);
    await page.locator('#tabTarifacion').click();
    const fee = page.locator('#tbodyVariable input').first();
    assert(await fee.count(), 'Fixture needs a tariff row');
    await fee.fill('987.65');
    await fee.press('Tab');
    await page.locator('#tabEstimacion').click();
    await page.locator('#tabTarifacion').click();
    assert.equal(await fee.inputValue(), '987.65', 'Changing views must preserve tariff draft');
    await page.locator('button[onclick="cargarVariable()"]').click();
    await page.waitForFunction(() => document.getElementById('estadoCargaVariable').dataset.state === 'success' && !document.getElementById('variableWorkspace').inert);
    assert.equal(await fee.inputValue(), '987.65', 'Refreshing same year must preserve tariff draft');
    await page.locator('#tabNextGen').click();
    assert.equal(await dollar.inputValue(), proposal);
    page.once('dialog', dialog => dialog.dismiss());
    await page.evaluate(async () => { document.getElementById('yearFiltro').value = '2027'; await cargarVariable(); });
    assert.equal(await page.locator('#yearFiltro').inputValue(), '2026');
    assert.equal(await dollar.inputValue(), proposal);
    await page.route('**/api/next-gen?*', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"success":false}' }));
    page.once('dialog', dialog => dialog.accept());
    await page.evaluate(async () => { document.getElementById('yearFiltro').value = '2027'; await cargarVariable(); });
    assert.equal(await page.locator('#yearFiltro').inputValue(), '2026', 'Failure must restore loaded year');
    assert.equal(await page.locator('#estadoCargaVariable').getAttribute('data-state'), 'error');
    assert.equal(await dollar.inputValue(), proposal);
    assert(await page.evaluate(() => cambiosTarifacion.size > 0 && cambiosDolarNextGen.size > 0));
    await page.unroute('**/api/next-gen?*');
    await page.route('**/api/next-gen/edicion-masiva', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"success":false,"errores":["Fallo de prueba"]}' }));
    await page.locator('#guardarCambiosNextGen').click();
    await page.waitForFunction(() => !guardandoNextGen);
    assert.equal(await dollar.inputValue(), proposal);
    assert.equal(await page.locator('#guardarCambiosNextGen').isEnabled(), true);
    assert.equal(await page.locator('#mensajeVariable').isVisible(), true, 'Next Gen errors must be visible outside the percentages panel');
    await page.locator('#tabTarifacion').click();
    await page.route('**/api/tarifaciones/edicion-masiva', route => route.abort('failed'));
    await page.locator('#guardarGrillaTarifacion').click();
    await page.waitForFunction(() => !guardandoTarifacion);
    assert.equal(await fee.inputValue(), '987.65');
    assert.equal(await page.locator('#guardarGrillaTarifacion').isEnabled(), true);
    assert.equal(await page.locator('#mensajeVariable').isVisible(), true, 'Tariff errors must remain visible');
    await page.screenshot({ path: '.cache/multiple-filters/variable-ux.png' });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: '.cache/multiple-filters/variable-ux-mobile.png', fullPage: true });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    assert.deepEqual(errors, []);
    console.log(`OK: Control ${total} registros paginados, nombres con comillas, edición cancelable y errores recuperables. Variable: pendientes conservados al alternar, actualizar, cancelar año y fallar consultas/guardados.`);
} catch (error) {
    console.error('Page errors:', errors);
    await page.screenshot({ path: '.cache/multiple-filters/operaciones-error.png', fullPage: true });
    throw error;
} finally {
    await browser.close();
}
