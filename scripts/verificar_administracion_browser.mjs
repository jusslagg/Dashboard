import {chromium} from 'playwright-core';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const fixture = JSON.parse(fs.readFileSync('.cache/administracion/browser.json','utf8'));
const browser = await chromium.launch({channel:'chrome',headless:true});
const context = await browser.newContext({viewport:{width:1440,height:1000}});
await context.addCookies([{...fixture.cookie,domain:'127.0.0.1',path:'/'}]);
const page = await context.newPage();
const errors = [];
page.on('pageerror',error => errors.push(error.message));
try {
    await page.goto('http://127.0.0.1:8012/administracion',{waitUntil:'networkidle'});
    await page.waitForFunction(() => !document.getElementById('adSave').disabled && document.querySelectorAll('.ad-check').length === 2);
    assert.equal(await page.locator('#adYear').inputValue(),'2026');
    await page.screenshot({path:'.cache/administracion/desktop.png'});
    await page.locator('#adYear').fill('2030');
    await page.locator('#adPassword').fill(fixture.password);
    await page.locator('#adSave').click();
    await page.waitForFunction(() => document.getElementById('adSettingsStatus').textContent.includes('guardado'));
    assert.equal(await page.locator('#adPassword').inputValue(),'');
    await page.locator('#adCalendar').check();
    assert(await page.locator('#adYear').evaluate(input => input.readOnly));
    await page.locator('#adPassword').fill(fixture.password);
    await page.locator('#adSave').click();
    await page.waitForFunction(() => document.getElementById('adSettingsStatus').textContent.includes('Avanzará'));
    await page.reload({waitUntil:'networkidle'});
    await page.waitForFunction(() => !document.getElementById('adSave').disabled);
    assert(await page.locator('#adCalendar').isChecked());
    await page.locator('#adCalendar').uncheck();
    assert(!(await page.locator('#adYear').evaluate(input => input.readOnly)));
    const external = await page.evaluate(async password => {
        const current = await (await fetch('/api/administracion/configuracion')).json();
        const response = await fetch('/api/administracion/configuracion',{method:'PATCH',headers:{'Content-Type':'application/json'},body:JSON.stringify({anio:2032,version:current.version,password_confirmacion:password})});
        return response.status;
    },fixture.password);
    assert.equal(external,200);
    await page.locator('#adYear').fill('2031');
    await page.locator('#adPassword').fill(fixture.password);
    await page.locator('#adSave').click();
    await page.waitForFunction(() => document.getElementById('adSettingsStatus').dataset.error === 'true');
    assert((await page.locator('#adSettingsStatus').innerText()).includes('Otra persona'));
    assert.equal(await page.locator('#adYear').inputValue(),'2031');
    page.once('dialog',dialog => dialog.accept());
    await page.locator('#adReload').click();
    await page.waitForFunction(() => document.getElementById('adYear').value === '2032');
    await page.route('**/api/administracion/pendientes?*',route => route.fulfill({status:500,contentType:'application/json',body:'{"success":false}'}));
    await page.locator('#adReview').click();
    await page.waitForFunction(() => document.getElementById('adReviewStatus').dataset.error === 'true');
    assert.equal(await page.locator('.ad-check').count(),0);
    await page.unroute('**/api/administracion/pendientes?*');
    await page.locator('#adReviewYear').fill('2026');
    await page.locator('#adReview').click();
    await page.waitForSelector('.ad-check');
    await page.locator('.ad-check summary').first().click();
    assert((await page.locator('.ad-check a').first().getAttribute('href')).startsWith('/catalogos'));
    await page.setViewportSize({width:390,height:844});
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({path:'.cache/administracion/mobile.png',fullPage:true});
    assert.equal(errors.length,0,errors.join('\n'));
    console.log('OK: admin load/save, conflict recovery, pending edits, read-only check error/retry and mobile layout.');
} finally { await browser.close(); }
